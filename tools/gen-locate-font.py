#!/usr/bin/env python3
"""Makes the "Locate game files" screen's font atlas: crates/render/src/locate_font.alpha (8-bit
coverage, WIDTH x HEIGHT) and crates/render/src/locate_font.rs (the glyph table), from Noto Sans
Regular (SIL Open Font License 1.1, https://openfontlicense.org; a rasterised subset may be
embedded). The screen cannot load the game's own font before the game is found.

    python3 tools/gen-locate-font.py [path to NotoSans-Regular.ttf]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZE = 28
WIDTH = 512
FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/noto/NotoSans-Regular.ttf"
CHARS = [chr(c) for c in range(32, 127)] + ["…", "›", "↑", "↓"]

font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
glyphs = []
x, y, row_h = 1, 1, 0
cells = []
for ch in CHARS:
    l, t, r, b = font.getbbox(ch, anchor="ls")
    w, h = max(r - l, 0), max(b - t, 0)
    adv = round(font.getlength(ch))
    if x + w + 1 > WIDTH:
        x, y, row_h = 1, y + row_h + 1, 0
    cells.append((ch, x, y, w, h, l, ascent + t, adv))
    x += w + 1
    row_h = max(row_h, h)
height = y + row_h + 1
# Draw each glyph with its bbox's top-left at its cell.
img = Image.new("L", (WIDTH, height), 0)
d = ImageDraw.Draw(img)
for ch, gx, gy, w, h, xo, yo, adv in cells:
    if w and h:
        l, t, r, b = font.getbbox(ch, anchor="ls")
        d.text((gx - l, gy - t), ch, font=font, fill=255, anchor="ls")
root = "crates/render/src/"
open(root + "locate_font.alpha", "wb").write(img.tobytes())
with open(root + "locate_font.rs", "w") as f:
    f.write("// Generated by tools/gen-locate-font.py from Noto Sans Regular (SIL OFL 1.1): do not edit.\n")
    f.write(f"pub const SIZE: f32 = {SIZE}.0;\npub const WIDTH: u32 = {WIDTH};\npub const HEIGHT: u32 = {height};\n")
    f.write("/// (char, x, y, width, height, x offset, y offset from the line's top, advance)\n")
    f.write("pub const GLYPHS: &[(char, u16, u16, u16, u16, i32, i32, u32)] = &[\n")
    for ch, gx, gy, w, h, xo, yo, adv in cells:
        lit = {"'": "'\\''", "\\": "'\\\\'"}.get(ch, f"'{ch}'")
        f.write(f"    ({lit}, {gx}, {gy}, {w}, {h}, {xo}, {yo}, {adv}),\n")
    f.write("];\n")
print("atlas", WIDTH, height, "line", ascent + descent)
