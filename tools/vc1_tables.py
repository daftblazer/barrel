#!/usr/bin/env python3
"""Generates crates/movie/src/vc1_tables.rs from SMPTE ST 421:2013 (VC-1), section 11.

Usage: pdftotext -layout st0421-2013.pdf st0421.txt
       python3 -I tools/vc1_tables.py st0421.txt > crates/movie/src/vc1_tables.rs

The standard is free from pub.smpte.org (doc/st421/20131008-pub/st0421-2013.pdf). Every
table is checked as it is read: indices without gaps, VLC codes prefix-free, scans
permutations of 0..63.
"""
import re
import sys

lines = open(sys.argv[1], encoding='utf-8').read().split('\n')
start = next(i for i, l in enumerate(lines) if l.startswith('11 Tables'))
title_re = re.compile(r'^\s*Table (\d+): (.*)$')

# Each table's lines, from its title to the next title (section 11 only).
tables = {}
current = None
for l in lines[start:]:
    if l.startswith('12 Bibliography'):
        break
    m = title_re.match(l)
    if m:
        current = int(m.group(1))
        tables[current] = (m.group(2).strip(), [])
    elif current is not None:
        tables[current][1].append(l)


ESCAPE = 1 << 30


def numeric_rows(body):
    """Rows of numbers only; the word ESCAPE (the DC tables' escape code) stands for an index
    after all the others."""
    for l in body:
        toks = l.split()
        if toks and all(re.fullmatch(r'-?\d+|ESCAPE', t) for t in toks):
            yield [ESCAPE if t == 'ESCAPE' else int(t) for t in toks]


def groups(number, k):
    """The table's numbers in groups of k, sorted by the first (the index)."""
    out = []
    for row in numeric_rows(tables[number][1]):
        if len(row) % k:
            raise SystemExit(f'table {number}: row of {len(row)} numbers: {row}')
        out += [row[i:i + k] for i in range(0, len(row), k)]
    out.sort(key=lambda g: g[0])
    if out and out[-1][0] == ESCAPE:
        out[-1][0] = out[-2][0] + 1
    idx = [g[0] for g in out]
    if idx != list(range(idx[0], idx[0] + len(idx))):
        raise SystemExit(f'table {number}: indices not contiguous ({idx[:5]}..., {len(idx)})')
    return out


def vlc(number):
    rows = groups(number, 3)
    if rows[0][0] != 0:
        raise SystemExit(f'table {number}: starts at {rows[0][0]}')
    codes = [(c, n) for _, c, n in rows]
    kraft = sum(2.0 ** -n for _, n in codes)
    if kraft > 1 + 1e-12:
        raise SystemExit(f'table {number}: Kraft sum {kraft}')
    for c, n in codes:
        if c >> n:
            raise SystemExit(f'table {number}: code {c} wider than {n}')
    strs = sorted(format(c, f'0{n}b') for c, n in codes)
    for a, b in zip(strs, strs[1:]):
        if b.startswith(a):
            raise SystemExit(f'table {number}: {a} is a prefix of {b}')
    return codes, kraft


def scan(number, size=64):
    """A scan table: its numbers stacked two lines a row, column by column."""
    body = [l for l in tables[number][1] if l.strip() and re.fullmatch(r'[\d ]+', l)]
    values = []
    if len(body) % 2:
        raise SystemExit(f'table {number}: {len(body)} lines, not tens/units pairs')
    # Each column reads top digit then bottom digit, whichever are there (the standard prints
    # single digits on either line).
    for top, bottom in zip(body[0::2], body[1::2]):
        for col in range(max(len(top), len(bottom))):
            digits = ''.join(line[col] for line in (top, bottom) if col < len(line) and line[col].isdigit())
            if digits:
                values.append(int(digits))
    if sorted(values) != list(range(size)):
        raise SystemExit(f'table {number}: not a permutation of 0..{size - 1}: {values}')
    return values


def ident(title):
    s = re.sub(r'[^A-Za-z0-9]+', '_', title).strip('_').upper()
    return s


out = ['// Generated by tools/vc1_tables.py from SMPTE ST 421:2013 section 11; do not edit.',
       '// VLC tables are (codeword, length) by index; run/level tables (run, level) by index;',
       '// delta tables the delta by run or level; scans the coefficient order.',
       '#![allow(dead_code)]', '']

vlc_tables = {
    168: 'I_CBPCY', 169: 'PB_CBPCY_0', 170: 'PB_CBPCY_1', 171: 'PB_CBPCY_2', 172: 'PB_CBPCY_3',
    246: 'MV_DIFF_0', 247: 'MV_DIFF_1', 248: 'MV_DIFF_2', 249: 'MV_DIFF_3',
    173: 'DC_LOW_LUMA', 174: 'DC_LOW_CHROMA', 175: 'DC_HIGH_LUMA', 176: 'DC_HIGH_CHROMA',
}
ac_sets = [(177, 'HIGH_MOTION_INTRA'), (184, 'HIGH_MOTION_INTER'), (191, 'LOW_MOTION_INTRA'),
           (198, 'LOW_MOTION_INTER'), (205, 'MID_RATE_INTRA'), (212, 'MID_RATE_INTER'),
           (219, 'HIGH_RATE_INTRA'), (226, 'HIGH_RATE_INTER')]
for n, name in vlc_tables.items():
    codes, kraft = vlc(n)
    out.append(f'/// Table {n}: {tables[n][0]} ({len(codes)} codes, Kraft sum {kraft:.6f}).')
    out.append(f'pub const {name}: [(u32, u8); {len(codes)}] = [' + ', '.join(f'({c}, {l})' for c, l in codes) + '];')
for n, name in ac_sets:
    codes, kraft = vlc(n)
    out.append(f'/// Table {n}: {tables[n][0]} ({len(codes)} codes, Kraft sum {kraft:.6f}; the last is the escape).')
    out.append(f'pub const {name}_VLC: [(u32, u8); {len(codes)}] = [' + ', '.join(f'({c}, {l})' for c, l in codes) + '];')
    for off, what in ((1, 'RUN_LEVEL_0'), (2, 'RUN_LEVEL_1')):
        rows = groups(n + off, 3)
        out.append(f'/// Table {n + off}: {tables[n + off][0]}.')
        out.append(f'pub const {name}_{what}: [(u8, u8); {len(rows)}] = [' + ', '.join(f'({r}, {lv})' for _, r, lv in rows) + '];')
    for off, what in ((3, 'DELTA_LEVEL_0'), (4, 'DELTA_LEVEL_1'), (5, 'DELTA_RUN_0'), (6, 'DELTA_RUN_1')):
        rows = groups(n + off, 2)
        first = rows[0][0]
        out.append(f'/// Table {n + off}: {tables[n + off][0]} (from {first}).')
        out.append(f'pub const {name}_{what}: [u8; {len(rows)}] = [' + ', '.join(str(d) for _, d in rows) + '];')
    # The run/level tables cover the codes before the escape.
    l0, l1 = len(groups(n + 1, 3)), len(groups(n + 2, 3))
    if l0 + l1 + 1 != len(codes):
        raise SystemExit(f'table {n}: {len(codes)} codes but {l0} + {l1} run/levels')
    out.append(f'pub const {name}_LAST_FROM: usize = {l0};')
for n, name, size in ((233, 'INTRA_NORMAL_SCAN', 64), (234, 'INTRA_HORIZONTAL_SCAN', 64), (235, 'INTRA_VERTICAL_SCAN', 64),
                      (236, 'INTER_8X8_SCAN', 64), (239, 'INTER_4X4_SCAN', 16), (240, 'INTER_8X4_SCAN', 32), (241, 'INTER_4X8_SCAN', 32)):
    s = scan(n, size)
    out.append(f'/// Table {n}: {tables[n][0]}.')
    out.append(f'pub const {name}: [u8; {size}] = [' + ', '.join(map(str, s)) + '];')
print('\n'.join(out))
