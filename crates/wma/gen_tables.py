#!/usr/bin/env python3
"""Writes src/tables.rs from FFmpeg's libavcodec/wmaprodata.h (LGPL 2.1 or later).

    python3 -I crates/wma/gen_tables.py path/to/wmaprodata.h > crates/wma/src/tables.rs

Each Huffman table comes out as (code, length, symbol) rows, the codes assigned the way FFmpeg's
ff_vlc_init_from_lengths assigns them: in table order, each code the running 32-bit counter's
top `length` bits, the counter then stepped by 2^(32 - length)."""
import re, sys

src = open(sys.argv[1]).read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)

def array(name):
    m = re.search(r'\b' + name + r'\s*\[[^\]]*\](?:\s*\[[^\]]*\])?\s*=\s*\{(.*?)\};', src, re.S)
    if not m:
        raise SystemExit('no ' + name)
    body = m.group(1).replace('{', ' ').replace('}', ' ')
    return [float(v) if '.' in v else int(v) for v in re.findall(r'-?[0-9.]+', body)]

def codes(lens, syms, offset):
    out, code = [], 0
    for l, s in zip(lens, syms):
        if l > 0:
            out.append((code >> (32 - l), l, s + offset))
        elif l == 0:
            continue
        code += 1 << (32 - abs(l))
    assert code <= 1 << 32
    return out

def pairs(name):
    v = array(name)
    return v[1::2], v[0::2]

tables = {
    'SCALE': codes(*pairs('scale_table'), -60),
    'SCALE_RL': codes(*pairs('scale_rl_table'), 0),
    'COEF0': codes(array('coef0_lens'), array('coef0_syms'), 0),
    'COEF1': codes(*pairs('coef1_table'), 0),
    'VEC4': codes(array('vec4_lens'), array('vec4_syms'), -1),
    'VEC2': codes(*pairs('vec2_table'), -1),
    'VEC1': codes(*pairs('vec1_table'), 0),
}
print('//! Generated by `gen_tables.py` from FFmpeg\'s `libavcodec/wmaprodata.h` (LGPL 2.1 or later).')
print('//! Huffman tables as (code, length, symbol).\n')
for name, rows in tables.items():
    print(f'pub const {name}: [(u32, u8, i16); {len(rows)}] = [' + ', '.join(f'({c}, {l}, {s})' for c, l, s in rows) + '];')
for name, rust, ty in [('scale_rl_run', 'SCALE_RL_RUN', 'u8'), ('scale_rl_level', 'SCALE_RL_LEVEL', 'u8'),
                       ('coef0_run', 'COEF0_RUN', 'u16'), ('coef1_run', 'COEF1_RUN', 'u16'),
                       ('coef0_level', 'COEF0_LEVEL', 'f32'), ('coef1_level', 'COEF1_LEVEL', 'f32')]:
    v = array(name)
    vals = ', '.join((f'{float(x)}' if ty == 'f32' else str(int(x))) for x in v)
    print(f'pub const {rust}: [{ty}; {len(v)}] = [{vals}];')
